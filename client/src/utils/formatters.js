/**
 * Format timestamp into human-readable date and time
 */
export function formatDateTime(isoString) {
  if (!isoString) return '';
  const date = new Date(isoString);
  if (isNaN(date.getTime())) return '';
  
  return date.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true
  });
}

/**
 * Format relative time (e.g. "just now", "4m ago")
 */
export function formatRelativeTime(isoString) {
  if (!isoString) return '';
  const now = new Date();
  const past = new Date(isoString);
  const diffInSeconds = Math.floor((now - past) / 1000);

  if (diffInSeconds < 30) return 'Just now';
  if (diffInSeconds < 60) return `${diffInSeconds}s ago`;
  const diffInMinutes = Math.floor(diffInSeconds / 60);
  if (diffInMinutes < 60) return `${diffInMinutes}m ago`;
  const diffInHours = Math.floor(diffInMinutes / 60);
  if (diffInHours < 24) return `${diffInHours}h ago`;
  const diffInDays = Math.floor(diffInHours / 24);
  if (diffInDays < 7) return `${diffInDays}d ago`;

  return formatDateTime(isoString);
}

/**
 * Truncate text with ellipsis
 */
export function truncate(str, max = 80) {
  if (!str) return '';
  return str.length > max ? str.substring(0, max) + '...' : str;
}

/**
 * Export diagnosis into clean Markdown for clipboard copying or exporting
 */
export function formatDiagnosisToMarkdown(entry) {
  const { errorMessage, technology, diagnosis, timestamp } = entry;
  if (!diagnosis) return '';

  const causes = (diagnosis.possibleCauses || [])
    .map((c, i) => `${i + 1}. ${c}`)
    .join('\n');

  const fixes = (diagnosis.recommendedFix || [])
    .map((f, i) => `${i + 1}. ${f}`)
    .join('\n');

  let codeSection = '';
  if (diagnosis.codeExample && (diagnosis.codeExample.originalCode || diagnosis.codeExample.correctedCode)) {
    codeSection = `
### 4. Code Example

**Problematic Code:**
\`\`\`${technology ? technology.toLowerCase() : ''}
${diagnosis.codeExample.originalCode}
\`\`\`

**Corrected Code:**
\`\`\`${technology ? technology.toLowerCase() : ''}
${diagnosis.codeExample.correctedCode}
\`\`\`

*Explanation:* ${diagnosis.codeExample.explanation}
`;
  }

  return `# AI Error Message Helper — Diagnosis Report
**Date:** ${formatDateTime(timestamp)}
**Technology:** ${technology || 'General'}

## Original Error Message
\`\`\`
${errorMessage}
\`\`\`

---

### 1. What Happened?
${diagnosis.summary}

### 2. Possible Causes
${causes}

### 3. Recommended Fix
${fixes}
${codeSection}
### 5. Prevention Tip
${diagnosis.preventionTip}

---
*Generated by AI Error Message Helper (Google Gemini Powered)*
`;
}

/**
 * Badge color mapping for technologies
 */
export function getTechBadgeClass(tech) {
  switch ((tech || '').toLowerCase()) {
    case 'javascript':
    case 'typescript':
      return 'badge-js';
    case 'react':
    case 'next.js':
      return 'badge-react';
    case 'python':
      return 'badge-python';
    case 'node.js':
    case 'express.js':
      return 'badge-node';
    case 'java':
    case 'c#':
      return 'badge-java';
    case 'c':
    case 'c++':
      return 'badge-cpp';
    case 'mongodb':
      return 'badge-mongo';
    case 'sql':
      return 'badge-sql';
    case 'php':
      return 'badge-php';
    default:
      return 'badge-default';
  }
}
